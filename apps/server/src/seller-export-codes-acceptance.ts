import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { migrate } from 'drizzle-orm/node-postgres/migrator';
import { eq } from 'drizzle-orm';
import { sellerExportCodeInputSchema } from '@scm/contracts';
import { db, closeDatabase } from './db/client.js';
import { user, sellerMappings, sellerExportCodes, operationAudit } from './db/schema.js';
import { listSellerExportCodes, saveSellerExportCode, readSellerExportCodes } from './modules/seller-mappings/export-codes.js';

globalThis.fetch = async () => { throw new Error('No remote requests allowed'); };
const actor = 'export-code-test', sid = 9876501;
try {
  const migrations = resolve(process.cwd(), 'drizzle'), baseline = resolve(process.env.DATA_DIR!, 'migration-before-text');
  const journal = JSON.parse(await readFile(resolve(migrations, 'meta/_journal.json'), 'utf8'));
  const entries = journal.entries.filter((entry: { idx: number }) => entry.idx <= 25);
  assert.equal(entries.at(-1).tag, '0025_pink_jack_flag');
  await mkdir(resolve(baseline, 'meta'), { recursive: true });
  await writeFile(resolve(baseline, 'meta/_journal.json'), JSON.stringify({ ...journal, entries }));
  for (const entry of entries) await copyFile(resolve(migrations, `${entry.tag}.sql`), resolve(baseline, `${entry.tag}.sql`));
  await migrate(db, { migrationsFolder: baseline });
  await db.insert(user).values({ id: actor, name: 'Fixture', email: 'codes@fixture.invalid', role: 'admin' });
  await db.insert(sellerMappings).values({ id: randomUUID(), sid, name: '测试店铺', country: '美国', sourceObservedAt: new Date(), sourceSha256: 'a'.repeat(64) });
  assert.equal((await listSellerExportCodes(actor)).items[0]!.code, '');
  const input = { operationId: randomUUID(), expectedVersion: 0, code: '001' };
  assert.deepEqual(await saveSellerExportCode(sid, input, actor), { code: '001', version: 1 });
  assert.deepEqual(await saveSellerExportCode(sid, input, actor), { code: '001', version: 1 });
  await assert.rejects(saveSellerExportCode(sid, { ...input, code: '002' }, actor), { code: 'OPERATION_CONFLICT' });
  await assert.rejects(saveSellerExportCode(sid, { ...input, operationId: randomUUID() }, actor), { code: 'VERSION_CONFLICT' });
  assert.equal((await readSellerExportCodes([sid])).get(sid), '001');
  await db.update(sellerMappings).set({ name: '重命名店铺' }).where(eq(sellerMappings.sid, sid));
  assert.equal((await listSellerExportCodes(actor)).items[0]!.code, '001');
  const beforeMigration = await db.select().from(sellerExportCodes);
  await migrate(db, { migrationsFolder: migrations });
  assert.deepEqual(await db.select().from(sellerExportCodes), beforeMigration);
  const textInput = { operationId: randomUUID(), expectedVersion: 1, code: ' 00Ab-1_@/+# ' };
  assert.deepEqual(await saveSellerExportCode(sid, textInput, actor), { code: '00Ab-1_@/+#', version: 2 });
  assert.deepEqual(await saveSellerExportCode(sid, textInput, actor), { code: '00Ab-1_@/+#', version: 2 });
  assert.equal((await readSellerExportCodes([sid])).get(sid), '00Ab-1_@/+#');
  const outcomes = await Promise.allSettled(['中文-03', 'A/04#'].map((code) => saveSellerExportCode(sid, { operationId: randomUUID(), expectedVersion: 2, code }, actor)));
  assert.equal(outcomes.filter((entry) => entry.status === 'fulfilled').length, 1);
  await saveSellerExportCode(sid, { operationId: randomUUID(), expectedVersion: 3, code: '' }, actor);
  assert.equal((await readSellerExportCodes([sid])).get(sid), '');
  for (const code of ['A01', '-1', '1.5', '001_@', '中文/#', '=1+1']) assert.equal(sellerExportCodeInputSchema.safeParse({ ...input, code }).success, true);
  for (const code of ['1'.repeat(21), 'A\u0001B', 'A\u007fB', 'A\u0085B']) assert.equal(sellerExportCodeInputSchema.safeParse({ ...input, code }).success, false);
  for (const code of ['1'.repeat(21), 'A\u0001B', 'A\u007fB']) await assert.rejects(db.transaction((tx) => tx.update(sellerExportCodes).set({ code }).where(eq(sellerExportCodes.sid, sid))), (error: unknown) => (error as { cause?: { code: string } }).cause?.code === '23514');
  assert.equal((await readSellerExportCodes([sid])).get(sid), '');
  await db.insert(user).values({ id: 'codes-banned', name: 'Banned', email: 'codes-banned@fixture.invalid', role: 'admin', banned: true });
  await assert.rejects(listSellerExportCodes('codes-banned'), { code: 'FORBIDDEN' });
  await assert.rejects(saveSellerExportCode(sid, { ...input, operationId: randomUUID() }, 'codes-banned'), { code: 'FORBIDDEN' });
  assert.equal((await db.select().from(operationAudit)).filter((entry) => entry.action === 'seller_export_code.save').length, 4);
  const result = { result: 'passed', checks: ['upgrade-from-numeric-constraint', 'existing-leading-zeros-preserved', 'persist-text-and-symbols', 'text-replay', 'operation-conflict', 'stale-version', 'sid-binding-after-rename', 'concurrent-text-update', 'clear', 'text-validation', 'database-length-and-control-constraint', 'authorization', 'audit'], realLingxingRequests: 0 };
  await writeFile(process.env.SERVICE_MAPPING_ACCEPTANCE_OUT!, JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result));
} finally { await closeDatabase(); }
